import { z } from "zod";

const MAX_RESUME_BYTES = 2 * 1024 * 1024;
const MAX_RESPONSE_BYTES = 1024 * 1024;
const identifier = z.string().regex(/^[A-Za-z0-9][A-Za-z0-9_-]{0,149}$/);
const inputSchema = z
  .object({
    board: identifier,
    postingId: identifier,
    apiKey: z
      .string()
      .trim()
      .min(1)
      .max(4096)
      .regex(/^[^\u0000-\u001f\u007f]+$/),
    fullName: z.string().trim().min(1).max(200),
    email: z.email().max(320),
    resume: z.custom(
      (value) =>
        Buffer.isBuffer(value) &&
        value.length > 0 &&
        value.length <= MAX_RESUME_BYTES,
      "Currículo deve ser um Buffer não vazio de até 2 MB",
    ),
    resumeName: z
      .string()
      .min(1)
      .max(200)
      .regex(/^[^/\\\u0000-\u001f\u007f]+\.(?:pdf|txt)$/i),
    comments: z.string().max(10000).optional(),
  })
  .strict();

/**
 * Errors contain only classification and operational metadata. Never include
 * the input, request URL (which contains the API key), or provider error body.
 */
export class SubmissionError extends Error {
  constructor(code, message, metadata = {}) {
    super(message);
    this.name = "SubmissionError";
    this.code = code;
    this.canRetry = code === "RATE_LIMIT";
    this.requiresReconciliation = code === "AMBIGUOUS";
    Object.assign(this, metadata);
  }
}

function validationError(fields = []) {
  return new SubmissionError(
    "VALIDATION",
    "Dados de candidatura inválidos; revise os campos indicados antes do envio.",
    { fields },
  );
}

function ambiguous(status) {
  return new SubmissionError(
    "AMBIGUOUS",
    "O resultado do envio é desconhecido. Confira a plataforma antes de tentar novamente.",
    status === undefined ? {} : { status },
  );
}

function rateLimitMetadata(header, currentTime) {
  // Do not retry immediately. Numeric and HTTP-date Retry-After values are
  // returned to the durable queue/worker, which must wait until retryAt.
  let retryAfterMs = 60000;
  if (header && /^\d+$/.test(header.trim())) {
    const seconds = Number(header.trim());
    if (
      Number.isSafeInteger(seconds) &&
      seconds * 1000 <= 8640000000000000 - currentTime
    )
      retryAfterMs = Math.max(1000, seconds * 1000);
    else return { retryAfterMs: null, retryAt: null, canRetry: false };
  } else if (header) {
    const timestamp = Date.parse(header);
    if (!Number.isNaN(timestamp))
      retryAfterMs = Math.max(1000, timestamp - currentTime);
  }
  return {
    retryAfterMs,
    retryAt: new Date(currentTime + retryAfterMs).toISOString(),
  };
}

async function readJson(response) {
  if (Number(response.headers.get("content-length")) > MAX_RESPONSE_BYTES)
    throw new Error("Response size limit");
  let size = 0;
  const chunks = [];
  for await (const chunk of response.body) {
    size += chunk.length;
    if (size > MAX_RESPONSE_BYTES) throw new Error("Response size limit");
    chunks.push(chunk);
  }
  return JSON.parse(Buffer.concat(chunks).toString("utf8"));
}

/**
 * Official Lever Postings API application endpoint, global instance only.
 * Requires an employer's API key generated by that Lever account's Super Admin.
 * A candidate's normal Lever/LinkedIn login does not authorize this endpoint.
 *
 * https://github.com/lever/postings-api#apply-to-a-job-posting
 *
 * The caller must have authorized this specific submission and must implement
 * the employer's additional required form fields/consents before using this
 * minimal connector for that board. No consent or missing answer is invented.
 * This function makes exactly one POST. A 429 is returned with retry timing;
 * an uncertain result must be reconciled rather than automatically repeated.
 */
export async function submitLeverApplication(
  input,
  { fetcher = fetch, timeoutMs = 20000, clock = Date.now, signal } = {},
) {
  if (signal?.aborted)
    throw new SubmissionError("CANCELLED", "Candidatura cancelada antes do envio.");
  if (typeof input?.apiKey !== "string" || !input.apiKey.trim())
    throw new SubmissionError(
      "MISSING_CREDENTIAL",
      "Falta uma chave da integração autorizada da empresa no Lever; senha de candidato não serve para este endpoint.",
    );

  const parsed = inputSchema.safeParse(input);
  if (!parsed.success)
    throw validationError([
      ...new Set(parsed.error.issues.map((issue) => issue.path.join("."))),
    ]);
  if (!Number.isInteger(timeoutMs) || timeoutMs < 1 || timeoutMs > 60000)
    throw validationError(["timeoutMs"]);

  const data = parsed.data;
  const pdf = /\.pdf$/i.test(data.resumeName);
  if (pdf && data.resume.subarray(0, 5).toString() !== "%PDF-")
    throw validationError(["resume"]);
  if (!pdf) {
    try {
      new TextDecoder("utf-8", { fatal: true }).decode(data.resume);
      if (data.resume.includes(0)) throw new Error("Binary text");
    } catch {
      throw validationError(["resume"]);
    }
  }

  const url = new URL(
    `https://api.lever.co/v0/postings/${encodeURIComponent(data.board)}/${encodeURIComponent(data.postingId)}`,
  );
  url.searchParams.set("key", data.apiKey);
  const body = new FormData();
  body.set("name", data.fullName);
  body.set("email", data.email);
  body.set(
    "resume",
    new Blob([data.resume], { type: pdf ? "application/pdf" : "text/plain" }),
    data.resumeName,
  );
  if (data.comments !== undefined) body.set("comments", data.comments);

  let response;
  try {
    response = await fetcher(url.toString(), {
      method: "POST",
      headers: {
        Accept: "application/json",
        "User-Agent": "VagaRadar/1.1 (authorized application integration)",
      },
      body,
      redirect: "error",
      signal: signal
        ? AbortSignal.any([signal, AbortSignal.timeout(timeoutMs)])
        : AbortSignal.timeout(timeoutMs),
    });
  } catch {
    // A timeout/network failure can happen after the platform accepted the POST.
    throw ambiguous();
  }

  if (response.status === 429) {
    const metadata = rateLimitMetadata(
      response.headers.get("retry-after"),
      clock(),
    );
    await response.body?.cancel().catch(() => {});
    throw new SubmissionError(
      "RATE_LIMIT",
      "O Lever recusou temporariamente o envio por limite de requisições; aguarde o prazo informado antes de reenfileirar.",
      { status: 429, ...metadata },
    );
  }
  if (response.status === 401 || response.status === 403) {
    await response.body?.cancel().catch(() => {});
    throw new SubmissionError(
      "AUTHORIZATION",
      "O Lever recusou a credencial ou a permissão de candidatura desta integração.",
      { status: response.status },
    );
  }
  if (
    response.status !== 200 &&
    (response.status < 400 || response.status >= 500 || response.status === 408)
  ) {
    await response.body?.cancel().catch(() => {});
    throw ambiguous(response.status);
  }

  let result;
  try {
    result = await readJson(response);
  } catch {
    throw ambiguous(response.status);
  }
  if (
    response.status === 200 &&
    result?.ok === true &&
    typeof result.applicationId === "string" &&
    /^[A-Za-z0-9][A-Za-z0-9_-]{0,199}$/.test(result.applicationId)
  )
    return {
      provider: "lever",
      applicationId: result.applicationId,
      board: data.board,
      postingId: data.postingId,
      submittedAt: new Date(clock()).toISOString(),
      verified: true,
    };
  if (result?.ok === false && typeof result.error === "string")
    throw new SubmissionError(
      "REJECTED",
      "O Lever recusou a candidatura. Revise os requisitos e campos específicos do formulário com a integração autorizada.",
      { status: response.status },
    );
  throw ambiguous(response.status);
}
